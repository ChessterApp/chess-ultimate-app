"""
Export the Tug of War offline fallback set from the Lichess puzzles DB.

Writes frontend/src/lib/tug-of-war/puzzles.ts: per level, a few puzzles of each
Tug of War theme (so the offline theme filter can be honored) topped up with
unthemed picks, already in the solving-position format of the live pack.
Read-only; seeded, so re-running gives the same file.

Usage (from backend/):
    venv/bin/python scripts/export_tug_fallback_puzzles.py [--per-level 75] [--per-theme 5]
"""

import argparse
import json
import os
import random
import sys

BACKEND = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, BACKEND)

from services import tug_pack  # noqa: E402
from services.puzzle_rush_source import PuzzleSource  # noqa: E402

OUT = os.path.join(BACKEND, '..', 'frontend', 'src', 'lib', 'tug-of-war', 'puzzles.ts')

HEADER = '''/**
 * Tug of War offline fallback puzzles — real Lichess puzzles, used only when
 * the backend pack endpoint is unreachable.
 *
 * GENERATED by backend/scripts/export_tug_fallback_puzzles.py — do not edit by
 * hand; re-run the exporter instead. Already in the solving-position format:
 * `fen` has the solver to move, `moves` is the remaining solution line.
 */
import type { TugPuzzle } from './types';

export const TUG_PUZZLES: TugPuzzle[] = [
'''


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--db', default=None, help='puzzles.db path (default: PUZZLE_RUSH_DB_PATH or hermes DB)')
    parser.add_argument('--per-level', type=int, default=75)
    parser.add_argument('--per-theme', type=int, default=5)
    parser.add_argument('--seed', type=int, default=20261018)
    args = parser.parse_args()

    source = PuzzleSource(args.db)
    rng = random.Random(args.seed)
    puzzles = []
    for level in tug_pack.LEVEL_BANDS:
        level_puzzles = []
        for theme in sorted(tug_pack.THEMES):
            level_puzzles += tug_pack.pack(level, [theme], args.per_theme, [p['id'] for p in puzzles + level_puzzles],
                                           source, rng)
        level_puzzles += tug_pack.pack(level, (), args.per_level - len(level_puzzles),
                                       [p['id'] for p in puzzles + level_puzzles], source, rng)
        puzzles += level_puzzles

    with open(OUT, 'w') as f:
        f.write(HEADER)
        f.writelines(f'  {json.dumps(p)},\n' for p in puzzles)
        f.write('];\n')
    print(f'wrote {len(puzzles)} puzzles to {os.path.normpath(OUT)}')


if __name__ == '__main__':
    main()
